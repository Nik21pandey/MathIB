"""
MathIB Polished PDF Report Generator
Produces clean, publication-ready A4 reports for Content Bifurcation & Syllabus Analysis.
Uses ReportLab with custom NumberedCanvas, running headers/footers, summary metric cards,
and auto-wrapped table styling with clean page breaks.
"""

import io
from datetime import datetime
from typing import Dict, Any, List

from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import mm, inch
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
    HRFlowable,
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT


class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print total page count ('Page X of Y')
    and running headers across all pages.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running Header (pages 2 and above)
        if self._pageNumber > 1:
            self.drawString(40, 805, "MathIB · Curriculum & Content Bifurcation Report")
            self.drawRightString(555, 805, datetime.now().strftime("%B %d, %Y"))
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(40, 798, 555, 798)

        # Running Footer (all pages)
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(40, 36, 555, 36)

        self.drawString(40, 24, "Generated by MathIB Intelligence Engine · Confidential & Pedagogical Resource")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(555, 24, page_text)

        self.restoreState()


def build_bifurcated_pdf_report(report_data: Dict[str, Any]) -> bytes:
    """
    Compiles structured bifurcation JSON into a polished, print-ready A4 PDF.
    """
    buffer = io.BytesIO()

    # 40pt (~14mm) margins left/right, 45pt top/bottom
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=40,
        rightMargin=40,
        topMargin=48,
        bottomMargin=48
    )

    styles = getSampleStyleSheet()

    # Custom styles
    brand_title_style = ParagraphStyle(
        'BrandTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0f172a")
    )

    brand_subtitle_style = ParagraphStyle(
        'BrandSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#475569")
    )

    meta_key_style = ParagraphStyle(
        'MetaKey',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#334155")
    )

    meta_val_style = ParagraphStyle(
        'MetaVal',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#0f172a")
    )

    section_heading_style = ParagraphStyle(
        'SectionHeading',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#1e293b")
    )

    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=11,
        textColor=colors.white,
        alignment=TA_LEFT
    )

    table_cell_style = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#1e293b")
    )

    table_topic_style = ParagraphStyle(
        'TableTopic',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#1e3a8a")
    )

    table_subtopic_style = ParagraphStyle(
        'TableSubtopic',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#475569")
    )

    table_justification_style = ParagraphStyle(
        'TableJustification',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#334155")
    )

    table_notes_style = ParagraphStyle(
        'TableNotes',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#64748b")
    )

    story = []

    # 1. Header Banner & Title Block
    title_text = "Content Bifurcation & Syllabus Structure Report"
    doc_filename = report_data.get("filename", "Uploaded_Document.pdf")
    subject = report_data.get("subject", "Mathematics")
    now_str = datetime.now().strftime("%B %d, %Y · %H:%M UTC")

    story.append(Paragraph("MathIB Intelligence", ParagraphStyle('SuperLogo', fontName='Helvetica-Bold', fontSize=10, leading=12, textColor=colors.HexColor("#2563eb"))))
    story.append(Spacer(1, 3))
    story.append(Paragraph(title_text, brand_title_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph(f"Curriculum-aligned structural extraction and difficulty analysis for <b>{subject}</b>.", brand_subtitle_style))
    story.append(Spacer(1, 10))

    # Metadata Grid (Source file, date, total pages, engine)
    meta_data = [
        [
            Paragraph("<b>Source File:</b>", meta_key_style),
            Paragraph(str(doc_filename), meta_val_style),
            Paragraph("<b>Date Generated:</b>", meta_key_style),
            Paragraph(now_str, meta_val_style)
        ],
        [
            Paragraph("<b>Analyzed Scope:</b>", meta_key_style),
            Paragraph(f"{report_data.get('pages_processed', report_data.get('total_pages', 1))} pages ({report_data.get('total_words', 0):,} words)", meta_val_style),
            Paragraph("<b>Classification Engine:</b>", meta_key_style),
            Paragraph(f"{report_data.get('engine', 'Academic Taxonomy Engine')}", meta_val_style)
        ]
    ]

    meta_table = Table(meta_data, colWidths=[80, 180, 95, 160])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#f1f5f9")),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 14))

    # 2. Executive Metrics Cards (Total, Beginner, Intermediate, Advanced)
    summary = report_data.get("summary", {})
    total_items = summary.get("total_items", len(report_data.get("items", [])))
    beg_cnt = summary.get("beginner_count", 0)
    inter_cnt = summary.get("intermediate_count", 0)
    adv_cnt = summary.get("advanced_count", 0)

    beg_pct = f"{round((beg_cnt / max(1, total_items)) * 100)}%"
    inter_pct = f"{round((inter_cnt / max(1, total_items)) * 100)}%"
    adv_pct = f"{round((adv_cnt / max(1, total_items)) * 100)}%"

    cards_data = [
        [
            Paragraph(f"<font color='#0f172a'><b>Total Units</b></font><br/><font size=16 color='#0f172a'><b>{total_items}</b></font><br/><font size=7 color='#64748b'>100% of curriculum items</font>", ParagraphStyle('Card1', alignment=TA_CENTER, leading=14)),
            Paragraph(f"<font color='#047857'><b>Beginner</b></font><br/><font size=16 color='#047857'><b>{beg_cnt}</b></font><br/><font size=7 color='#065f46'>{beg_pct} of breakdown</font>", ParagraphStyle('Card2', alignment=TA_CENTER, leading=14)),
            Paragraph(f"<font color='#b45309'><b>Intermediate</b></font><br/><font size=16 color='#b45309'><b>{inter_cnt}</b></font><br/><font size=7 color='#92400e'>{inter_pct} of breakdown</font>", ParagraphStyle('Card3', alignment=TA_CENTER, leading=14)),
            Paragraph(f"<font color='#6d28d9'><b>Advanced</b></font><br/><font size=16 color='#6d28d9'><b>{adv_cnt}</b></font><br/><font size=7 color='#5b21b6'>{adv_pct} of breakdown</font>", ParagraphStyle('Card4', alignment=TA_CENTER, leading=14))
        ]
    ]

    cards_table = Table(cards_data, colWidths=[128, 128, 128, 128])
    cards_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, 0), colors.HexColor("#f1f5f9")),
        ('BACKGROUND', (1, 0), (1, 0), colors.HexColor("#ecfdf5")),
        ('BACKGROUND', (2, 0), (2, 0), colors.HexColor("#fffbeb")),
        ('BACKGROUND', (3, 0), (3, 0), colors.HexColor("#f5f3ff")),
        ('BOX', (0, 0), (0, 0), 1, colors.HexColor("#cbd5e1")),
        ('BOX', (1, 0), (1, 0), 1, colors.HexColor("#a7f3d0")),
        ('BOX', (2, 0), (2, 0), 1, colors.HexColor("#fde68a")),
        ('BOX', (3, 0), (3, 0), 1, colors.HexColor("#ddd6fe")),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(cards_table)
    story.append(Spacer(1, 16))

    # 3. Structured Bifurcation Breakdown Table
    story.append(Paragraph("Structured Content Hierarchy & Difficulty Analysis", section_heading_style))
    story.append(Spacer(1, 6))

    table_data = [
        [
            Paragraph("<b>Unit / Marks</b>", table_header_style),
            Paragraph("<b>Topic & Subtopic</b>", table_header_style),
            Paragraph("<b>Difficulty</b>", table_header_style),
            Paragraph("<b>Source</b>", table_header_style),
            Paragraph("<b>Pedagogical Justification & Concepts</b>", table_header_style)
        ]
    ]

    items = report_data.get("items", [])
    for idx, item in enumerate(items):
        item_num = idx + 1
        unit_ref = item.get("unit_ref", f"Q{item_num}")
        marks = item.get("marks")
        marks_str = f"<br/><font size=7 color='#475569'><b>[{marks} marks]</b></font>" if marks else ""
        diagram_flag = "<br/><font size=6 color='#2563eb'>● Diagram</font>" if item.get("has_diagram") else ""
        topic = item.get("topic", "General")
        subtopic = item.get("subtopic", "Concept")
        diff = item.get("difficulty", "Intermediate")
        page_ref = item.get("page_ref", "N/A")
        justification = item.get("justification", "")
        notes = item.get("key_notes", "")

        # Format difficulty badge
        if diff == "Beginner":
            diff_html = "<font color='#047857'><b>● Beginner</b></font>"
        elif diff == "Advanced":
            diff_html = "<font color='#7c3aed'><b>▲ Advanced</b></font>"
        else:
            diff_html = "<font color='#b45309'><b>■ Intermediate</b></font>"

        topic_cell = [
            Paragraph(topic, table_topic_style),
            Spacer(1, 2),
            Paragraph(subtopic, table_subtopic_style)
        ]

        justification_cell = [
            Paragraph(f"<b>Justification:</b> {justification}", table_justification_style),
            Spacer(1, 2),
            Paragraph(f"<b>Focus:</b> {notes}", table_notes_style)
        ]

        table_data.append([
            Paragraph(f"<b>{unit_ref}</b>{marks_str}{diagram_flag}", table_cell_style),
            topic_cell,
            Paragraph(diff_html, table_cell_style),
            Paragraph(page_ref, table_cell_style),
            justification_cell
        ])

    # Table column widths sum to 515pt (printable A4 width)
    # 35 + 125 + 75 + 45 + 235 = 515 pt
    main_table = Table(
        table_data,
        colWidths=[35, 125, 75, 45, 235],
        repeatRows=1
    )

    t_style = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#0f172a")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ]

    # Alternating row backgrounds
    for r in range(1, len(table_data)):
        bg_col = colors.HexColor("#ffffff") if r % 2 == 1 else colors.HexColor("#f8fafc")
        t_style.append(('BACKGROUND', (0, r), (-1, r), bg_col))

    main_table.setStyle(TableStyle(t_style))
    story.append(main_table)

    # Build PDF with dynamic header/footer
    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()
